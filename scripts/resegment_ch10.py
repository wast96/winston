def build_pagemap():
    body_texts = [text for k, text in ITEMS if k == 'b']
    pm = []
    for printed, pdf, prefix in PAGE_STARTS:
        idx = next((i for i, t in enumerate(body_texts) if t.startswith(prefix)),
                   None)
        if idx is None:
            raise SystemExit('pagemap: prefix not matched: %r' % prefix)
        pm.append({'printed': printed, 'pdf': pdf, 'body_paragraph': idx})
    for a, b in zip(pm, pm[1:]):
        if b['body_paragraph'] <= a['body_paragraph']:
            raise SystemExit('pagemap: non-increasing at printed %d (idx %d <= %d)'
                             % (b['printed'], b['body_paragraph'],
                                a['body_paragraph']))
    return pm


